"""Build results/REPORT.md from results/final_<model>_<set>.json (written by run_final_eval.sh).

Everything in the report is computed from the per-example result files; nothing is typed in by hand.
"""
import json
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
R = ROOT / "results"
SETS = ["test", "unseen", "testpeak"]
CLASSES = ["engine", "helicopter", "drone", "wind", "siren", "gunshot", "artillery", "mixed"]
SNR_BINS = [-10, -5, 0, 5, 10, 15]
PEAK_MIN = 140


def load(tag, s):
    p = R / f"final_{tag}_{s}.json"
    return {e["file"]: e for e in json.load(open(p))} if p.exists() else None


def sel(rows, s, cls=None):
    out = []
    for e in rows.values():
        if s == "testpeak" and e["key"] < PEAK_MIN:
            continue
        if cls and e["cls"] != cls:
            continue
        out.append(e)
    return out


def m(es, f):
    v = [f(e) for e in es]
    v = [x for x in v if x == x]
    return float(np.mean(v)) if v else float("nan")


dsi = lambda e: e["sisnr"] - e["sisnr_in"]
stoi = lambda e: e["stoi"]
pesq = lambda e: e["pesq"]


def row(tag, label=None):
    cells = [f"{label or tag}"]
    for s in SETS:
        r = load(tag, s)
        es = sel(r, s) if r else []
        cells += [f"{m(es, dsi):+.1f}", f"{m(es, stoi):.3f}", f"{m(es, pesq):.2f}"] if es else ["-", "-", "-"]
    so = load(tag, "speechonly")
    cells.append(f"{m(list(so.values()), lambda e: e['sisnr']):.1f}" if so else "-")
    return "| " + " | ".join(cells) + " |"


def paired(a, b, s, f, rng, n=2000):
    A, B = load(a, s), load(b, s)
    if not A or not B:
        return None
    files = [k for k in A if k in B and (s != "testpeak" or A[k]["key"] >= PEAK_MIN)]
    d = np.array([f(A[k]) - f(B[k]) for k in files], float)
    d = d[~np.isnan(d)]
    if len(d) == 0:
        return None
    idx = rng.integers(0, len(d), (n, len(d)))
    mm = d[idx].mean(1)
    return d.mean(), np.percentile(mm, 2.5), np.percentile(mm, 97.5)


def fmt(ci, prec=2):
    if ci is None:
        return "-"
    mean, lo, hi = ci
    star = "*" if lo > 0 or hi < 0 else ""
    return f"{mean:+.{prec}f} [{lo:+.{prec}f}, {hi:+.{prec}f}]{star}"


def main():
    rng = np.random.default_rng(0)
    L = ["# Results\n",
         "Generated by `scripts/make_report.py` from `results/final_*.json`. Test sets are fixed, use held-out speakers "
         "(LibriSpeech test-clean) and held-out gunshot events; `unseen` uses shifted noise parameters and a held-out "
         "firearm (12-gauge shotgun). *dSI-SNR* = SI-SNR improvement over the unprocessed primary microphone. "
         "`*` after a difference means the 95% paired-bootstrap interval excludes 0 (evaluation noise only, "
         "not training-seed variance).\n"]

    models = [("none", "no processing"), ("gtcrn", "pretrained GTCRN (single mic)"),
              ("nlms_only", "NLMS only (gated)"),
              ("A_mono_s0", "Small, single mic, fine-tuned"), ("B_ref_s0", "Small + reference mic"),
              ("C_full_s0", "Small + reference + impulse flag"), ("D_fulldrop_s0", "  + reference dropout 0.2"),
              ("A_mono_s1", "Small, single mic (seed 1)"), ("C_full_s1", "Small + ref + flag (seed 1)"),
              ("T_tiny_s0", "Tiny, from scratch"), ("L_base_s0", "Base, from scratch"),
              ("C_full_s0_nlmspost", "C + NLMS after network"), ("C_full_s0_nlmspre", "C + NLMS before network (not retrained)"),
              ("E_nlmspre_s0", "Small trained with NLMS before network"),
              ("G_noimpw_s0", "Small + ref, NO impulse-frame loss weight")]
    L += ["\n## 1. Overall (mean over all classes and SNR bins)\n",
          f"Weapon set = close-range peaks >= {PEAK_MIN} dB SPL only.\n",
          "| model | test dSI-SNR | STOI | PESQ | unseen dSI-SNR | STOI | PESQ | weapons dSI-SNR | STOI | PESQ | speech-only SI-SNR |",
          "|---|---|---|---|---|---|---|---|---|---|---|"]
    L += [row(t, lbl) for t, lbl in models if load(t, "test") or load(t, "testpeak")]

    main = next((t for t in ("C_full_s0", "B_ref_s0", "A_mono_s0") if load(t, "test")), None)
    if main:
        L += [f"\n## 2. Per class, main model ({main}) vs pretrained GTCRN vs no processing (test set)\n",
              "| class | none STOI | none PESQ | GTCRN dSI-SNR | STOI | PESQ | ours dSI-SNR | STOI | PESQ |", "|---|---|---|---|---|---|---|---|---|"]
        n0, g0, o0 = load("none", "test"), load("gtcrn", "test"), load(main, "test")
        for c in CLASSES:
            if n0 and g0 and o0:
                a, b, o = sel(n0, "test", c), sel(g0, "test", c), sel(o0, "test", c)
                L.append(f"| {c} | {m(a, stoi):.2f} | {m(a, pesq):.2f} | {m(b, dsi):+.1f} | {m(b, stoi):.2f} | {m(b, pesq):.2f} | "
                         f"{m(o, dsi):+.1f} | {m(o, stoi):.2f} | {m(o, pesq):.2f} |")

        L += [f"\n## 3. Statement targets, main model ({main}), test set\n",
              "Each cell: S = output SI-SNR > 15 dB, T = STOI > 0.85, P = PESQ > 2.5 (mean over the cell's clips); `.` = not met.\n",
              "| class | " + " | ".join(f"{b:+d} dB" for b in SNR_BINS) + " |", "|---|" + "---|" * len(SNR_BINS)]
        for c in CLASSES:
            cells = []
            for b in SNR_BINS:
                es = [e for e in o0.values() if e["cls"] == c and e["key"] == b]
                if not es:
                    cells.append("-")
                    continue
                s_, t_, p_ = m(es, lambda e: e["sisnr"]), m(es, stoi), m(es, pesq)
                cells.append(("S" if s_ > 15 else ".") + ("T" if t_ > 0.85 else ".") + ("P" if p_ > 2.5 else "."))
            L.append(f"| {c} | " + " | ".join(cells) + " |")

    L += ["\n## 4. Ablations (paired differences: first minus second; mean [95% interval])\n",
          "| question | comparison | test dSI-SNR | test STOI | test PESQ | weapons STOI | weapons PESQ |", "|---|---|---|---|---|---|---|"]
    pairs = [("Does the reference mic help?", "B_ref_s0", "A_mono_s0"),
             ("Does the impulse flag help?", "C_full_s0", "B_ref_s0"),
             ("Does reference dropout help/hurt?", "D_fulldrop_s0", "C_full_s0"),
             ("Full system vs single mic (seed 0)", "C_full_s0", "A_mono_s0"),
             ("Full system vs single mic (seed 1)", "C_full_s1", "A_mono_s1"),
             ("Seed-to-seed variation (same config)", "C_full_s0", "C_full_s1"),
             ("Fine-tuned single mic vs pretrained", "A_mono_s0", "gtcrn"),
             ("Full system vs pretrained", "C_full_s0", "gtcrn"),
             ("Does the impulse-frame loss weighting matter?", "B_ref_s0", "G_noimpw_s0"),
             ("Tiny vs Small", "T_tiny_s0", "C_full_s0"),
             ("Base vs Small", "L_base_s0", "C_full_s0"),
             ("NLMS after the network", "C_full_s0_nlmspost", "C_full_s0"),
             ("NLMS before the network (model not retrained)", "C_full_s0_nlmspre", "C_full_s0"),
             ("NLMS before the network, trained with it", "E_nlmspre_s0", "C_full_s0")]
    for q, a, b in pairs:
        cells = [fmt(paired(a, b, "test", dsi, rng), 2), fmt(paired(a, b, "test", stoi, rng), 3), fmt(paired(a, b, "test", pesq, rng), 3),
                 fmt(paired(a, b, "testpeak", stoi, rng), 3), fmt(paired(a, b, "testpeak", pesq, rng), 3)]
        if all(c == "-" for c in cells):
            continue
        L.append(f"| {q} | {a} - {b} | " + " | ".join(cells) + " |")

    L += ["\n## 5. Speech-only distortion (no noise; speech leaks into the reference mic)\n",
          "SI-SNR of the output against the clean target. Higher is better; the unprocessed value is the ceiling set by the "
          "dereverberating target, not by any processing.\n", "| system | speech-only SI-SNR (dB) | STOI |", "|---|---|---|"]
    for t, lbl in [("none", "no processing"), ("gtcrn", "pretrained GTCRN"), ("C_full_s0", "our model"),
                   ("nlms_only", "NLMS only, gated"), ("nlms_only_nogate", "NLMS only, gate OFF")]:
        so = load(t, "speechonly")
        if so:
            L.append(f"| {lbl} | {m(list(so.values()), lambda e: e['sisnr']):.1f} | {m(list(so.values()), stoi):.3f} |")

    # ---------------- phase 2 sections
    def p2(name):
        path = R / name
        return {e["file"]: e for e in json.load(open(path))} if path.exists() else None

    base = load("C_full_s0", "test")
    if base:
        even = [e for i, e in enumerate(base.values()) if i % 2 == 0]
        prune = [("dense (C_full_s0, same clips)", even)]
        prune += [(f"{s}% pruned + fine-tuned", list(r.values())) for s in (30, 50, 70) if (r := p2(f"p2_prune{s}_test.json"))]
        if len(prune) > 1:
            L += ["\n## 7. Pruning (Small model, global magnitude pruning, 1,500 fine-tuning steps; every 2nd test clip)\n",
                  "Unstructured sparsity reduces the parameter count but does not speed up ONNX Runtime on a CPU.\n",
                  "| variant | dSI-SNR | STOI | PESQ |", "|---|---|---|---|"]
            for lbl, es in prune:
                L.append(f"| {lbl} | {m(es, dsi):+.2f} | {m(es, stoi):.3f} | {m(es, pesq):.2f} |")

        g = load("gtcrn", "test")
        rows8 = []
        for cls in ("drone", "gunshot"):
            held = p2(f"p2_no{cls}_test.json")
            if held and g:
                a_, b_, c_ = sel(held, "test", cls), sel(base, "test", cls), sel(g, "test", cls)
                rows8.append(f"| {cls} | {m(b_, dsi):+.1f} / {m(b_, stoi):.3f} / {m(b_, pesq):.2f} | "
                             f"{m(a_, dsi):+.1f} / {m(a_, stoi):.3f} / {m(a_, pesq):.2f} | {m(c_, dsi):+.1f} / {m(c_, stoi):.3f} / {m(c_, pesq):.2f} |")
        if rows8:
            L += ["\n## 8. Held-out noise class (dSI-SNR / STOI / PESQ on that class, test set)\n",
                  "'Without it' models never saw the class during training.\n",
                  "| class | trained with it | trained without it | pretrained GTCRN |", "|---|---|---|---|"] + rows8

    faults = {"none": "normal", "zero": "reference dead (all zeros)", "copy": "reference = copy of primary",
              "loud": "reference +10 dB", "quiet": "reference -10 dB", "shifted": "reference delayed 5 ms"}
    frows = []
    for f, lbl in faults.items():
        cells = []
        for mdl in ("A_mono_s0", "C_full_s0", "D_fulldrop_s0"):
            r = p2(f"p2_fault_{mdl}_{f}.json")
            cells.append(f"{m(list(r.values()), dsi):+.2f} / {m(list(r.values()), stoi):.3f}" if r else "-")
        frows.append(f"| {lbl} | " + " | ".join(cells) + " |")
    if p2("p2_fault_C_full_s0_zero.json"):
        L += ["\n## 9. Reference-microphone faults (dSI-SNR / STOI, every 3rd test clip)\n",
              "The single-mic model does not use the reference, so it is the control. Dropout training is meant to make the "
              "two-mic model survive a failed reference.\n",
              "| condition | single mic | two mic + flag | + reference dropout |", "|---|---|---|---|"] + frows

    if p2("p4_fault_H_robust_s0_zero.json"):
        L += ["\n## 10. Robust deployment model and the reference guard (dSI-SNR / STOI, every 3rd test clip)\n",
              "Guard = runtime copy-detector (`src/anc/refguard.py`): a reference strongly correlated with the primary above 1.5 kHz is "
              "replaced by silence. It needs about 0.4 s to react, and this clip-average includes that first stretch. "
              "H = trained with reference dropout 0.2 and +/-8 dB gain mismatch.\n",
              "| condition | D (dropout), no guard | D + guard | H (robust) + guard |", "|---|---|---|---|"]
        for f, lbl in faults.items():
            cells = []
            for name in (f"p2_fault_D_fulldrop_s0_{f}.json", f"p4_fault_D_fulldrop_s0_{f}.json", f"p4_fault_H_robust_s0_{f}.json"):
                r = p2(name)
                cells.append(f"{m(list(r.values()), dsi):+.2f} / {m(list(r.values()), stoi):.3f}" if r else "-")
            L.append(f"| {lbl} | " + " | ".join(cells) + " |")
        hn = load("H_robust_s0", "test")
        if hn and base:
            L += ["", "Normal-condition cost of the robust training (full test set):\n", "| model | dSI-SNR | STOI | PESQ |", "|---|---|---|---|"]
            for lbl, r in (("C (no dropout)", base), ("D (dropout 0.2)", load("D_fulldrop_s0", "test")), ("H (dropout + wide mismatch)", hn)):
                if r:
                    es = list(r.values())
                    L.append(f"| {lbl} | {m(es, dsi):+.2f} | {m(es, stoi):.3f} | {m(es, pesq):.2f} |")

    dp = {k: p2(f"deployed_{k}_test.json") for k in ("fp32", "int8")}
    hn_all = load("H_robust_s0", "test")
    if dp["fp32"] and hn_all:
        files = [f for f in dp["fp32"] if f in hn_all and (not dp["int8"] or f in dp["int8"])]
        pick = lambda d: [d[f] for f in files]
        L += ["\n## 11. The deployed path (what will run on the Pi): NumPy front end + ONNX Runtime + guard + slow level control\n",
              f"Robust Small model (H), {len(files)} test clips (every 2nd). The PyTorch row normalises each clip by its own RMS; the "
              "deployed rows use the streaming runtime with a ~1.5 s automatic level control.\n",
              "| path | dSI-SNR | STOI | PESQ |", "|---|---|---|---|"]
        rows11 = [("PyTorch offline", hn_all), ("deployed ONNX float32", dp["fp32"])] + ([("deployed ONNX INT8 (dynamic)", dp["int8"])] if dp["int8"] else [])
        for lbl, d in rows11:
            es = pick(d)
            L.append(f"| {lbl} | {m(es, dsi):+.2f} | {m(es, stoi):.3f} | {m(es, pesq):.2f} |")
        wp = p2("deployed_fp32_testpeak.json")
        wo = load("H_robust_s0", "testpeak")
        if wp and wo:
            a_, b_ = [e for e in wp.values() if e["key"] >= PEAK_MIN], sel(wo, "testpeak")
            L += ["", f"Close-range weapons (peaks >= {PEAK_MIN} dB SPL): PyTorch offline STOI {m(b_, stoi):.3f} / PESQ {m(b_, pesq):.2f}; "
                  f"deployed float32 STOI {m(a_, stoi):.3f} / PESQ {m(a_, pesq):.2f}."]

    L += ["\n## 6. What these numbers do and do not show\n",
          "- All noise is synthetic or from public recordings; speech leakage and the reference-mic geometry are simulated, "
          "not measured on the real headset. Real-hardware validation is a separate step.",
          "- One training seed per configuration except where a second seed is listed; the seed-to-seed row above is "
          "the yardstick for how large a difference must be to mean anything.",
          "- PESQ/SI-SNR benefit partly from the dereverberating target (direct sound + 5 ms).",
          "- Energy-based SNR overstates how easy impulsive noise is; the weapon set (level set by peak SPL) is the harder test.",
          "- INT8 and Raspberry Pi timing are reported separately (they need the device)."]
    (R / "REPORT.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print("wrote", R / "REPORT.md")


if __name__ == "__main__":
    main()
